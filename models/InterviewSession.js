const mongoose = require('mongoose');

// One practice interview. The model service's report is stored as-is in `report`
// so new fields from the model team need no schema change.
const interviewSessionSchema = new mongoose.Schema(
  {
    sessionId: { type: String, required: true, unique: true }, // generated by the model service (itv_xxx)
    userId: { type: mongoose.Schema.Types.ObjectId, ref: 'User', required: true, index: true },
    mode: { type: String, enum: ['single', 'panel', 'group'], required: true },
    config: { type: mongoose.Schema.Types.Mixed, default: {} }, // frontend settings: targetJobTitle, round, difficulty...
    participants: { type: [mongoose.Schema.Types.Mixed], default: [] }, // personas from the opening call, keep `role`
    turns: { type: [mongoose.Schema.Types.Mixed], default: [] },
    groupSays: { type: [mongoose.Schema.Types.Mixed], default: [] }, // all speakers, with isUser
    report: { type: mongoose.Schema.Types.Mixed, required: true },
    overallScore: { type: Number, default: null }, // pending three-team decision
  },
  { timestamps: true }
);

module.exports = mongoose.model('InterviewSession', interviewSessionSchema, 'interview_sessions');
