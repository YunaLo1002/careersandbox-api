const mongoose = require('mongoose');

// One finished mock interview: the model service's report plus the transcript
// it was built from. The report is stored as-is (Mixed) so its shape can
// follow the model team's contract without schema changes on our side.
//
// Deliberately NOT stored:
// - probeGap / probeDepth: per-turn transport state for the stateless
//   interview service, meaningless once the interview is over.
// - experiences: already in the experiences collection; see resumeVersionId.
// - askedQuestions: duplicates turns[].question.
// - interview stage: derived from followUpIdx, so storing it would go stale
//   the day the formula changes.
const interviewSessionSchema = new mongoose.Schema(
  {
    // Generated by the interview service (itv_xxx).
    sessionId: { type: String, required: true, unique: true },
    userId: { type: mongoose.Schema.Types.ObjectId, ref: 'User', required: true, index: true },
    mode: { type: String, enum: ['single', 'panel', 'group'], required: true },

    config: { type: mongoose.Schema.Types.Mixed, default: {} },

    // Personas from POST /interviews, stored whole (id, displayName, role,
    // blurb). Group competitors are generated per session, so replaying an
    // old group interview needs the original set.
    participants: { type: [mongoose.Schema.Types.Mixed], default: [] },

    // Each turn may carry inputMode, answerSegments, segmentStartsMs,
    // segmentEndsMs and endedBy; kept verbatim so a session can be re-analysed.
    turns: { type: [mongoose.Schema.Types.Mixed], default: [] },
    groupSays: { type: [mongoose.Schema.Types.Mixed], default: [] },

    // Skills extracted from the JD at interview start, in priority order.
    // Scoring depends on the order, so never sort or de-duplicate it.
    // Kept so a re-run does not need another (possibly different) extraction.
    jdSkills: { type: [String], default: [] },

    // The interviewer's opening line from POST /interviews. It is assembled by
    // code rather than generated, but stored anyway: if the assembly logic
    // changes, a re-run must not put words in the transcript that were never said.
    openingIntro: { type: String, default: '' },

    // Which resume version the user practised with. Only the id and label are
    // kept, not a copy of the experiences. The version can be edited later;
    // together with createdAt this tells the user which version, as of when,
    // the report was based on.
    resumeVersionId: { type: String, default: '' },
    resumeVersionLabel: { type: String, default: '' },

    report: { type: mongoose.Schema.Types.Mixed, required: true },

    // Summary number computed by the model service (not a simple average).
    // Stays null until the model team ships it. scoreBasis lists which
    // sub-scores went into it, e.g. fluency is left out for very short answers.
    overallScore: { type: Number, default: null, min: 0, max: 100 },
    scoreBasis: { type: [String], default: [] },
  },
  { timestamps: true }
);

module.exports = mongoose.model('InterviewSession', interviewSessionSchema, 'interview_sessions');
